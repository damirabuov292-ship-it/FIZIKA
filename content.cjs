  function round(x, d) { const k = Math.pow(10, d); return Math.round(x * k) / k; }
  function fmt(x) {
    if (typeof x !== "number") return String(x);
    const r = round(x, 3);
    return String(r).replace(".", ",").replace(/^-/, "−");
  }
  /* Сандық есепті көп нұсқалы сұраққа айналдыру (жауап solve() арқылы) */
  function buildProblem(p) {
    const v = {}; p.given.forEach(([k, val]) => (v[k] = val));
    const exact = p.solve(v);
    const ans = round(exact, p.round ?? 3);
    const eq = Math.abs(exact - ans) > 1e-9 ? "≈" : "=";
    const opts = [ans, ...p.wrong.map((w) => round(w, 3))];
    // қайталанатын нұсқа болмауы керек
    const uniq = new Set(opts.map(String));
    if (uniq.size !== opts.length) throw new Error("Қайталанған нұсқа: " + p.id);
    return {
      id: p.id, topic: p.topic, level: p.level, kind: "numeric", text: p.text,
      options: opts.map((o) => `${fmt(o)} ${p.unit}`.trim()), correct: 0, answer: ans, unit: p.unit,
      solution: {
        given: p.given.map(([k, val, u]) => `${k} = ${fmt(val)} ${u}`.trim()),
        find: p.find, formula: p.formula, transform: p.transform,
        calc: `${p.calc(v).replace(/(\d)\.(\d)/g, "$1,$2")} ${eq} ${fmt(ans)} ${p.unit}`.trim(),
        answer: `${p.find} ${eq} ${fmt(ans)} ${p.unit}`.trim(),
      },
    };
  }
